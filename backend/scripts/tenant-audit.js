// SaaS phase 0: inventory of what the multi-shop (tenant) conversion has to touch.
// Read-only — parses src/db/init.js and src/routes/*.js, never connects to a database.
//   node scripts/tenant-audit.js            → prints the report
//   node scripts/tenant-audit.js --write    → also writes ../docs/saas-tenant-audit.md
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const init = fs.readFileSync(path.join(SRC, 'db', 'init.js'), 'utf8');

// ── how each table is treated in the conversion ──
// legacy: old rack / wing-arm stock, being retired in favour of the combined stock (สต๊อกรวม)
// child: rows only ever reached through a parent row (FK) — inherit the parent's shop
// global: shared reference data, same for every shop
// (everything else) root: gets its own shop_id column
const LEGACY = new Set(['racks', 'wing_arms', 'rack_fitments', 'wing_arm_fitments', 'transactions']);
const CHILD = new Set([
  'quotation_items', 'receipt_items', 'receipt_payments', 'claim_items', 'job_status_history', 'job_photos',
  'service_item_components', 'stock_item_positions', 'stock_item_fitments', 'stock_item_movements',
  'stock_receive_lines', 'stock_count_items', 'part_codes', 'part_fitments',
]);
const GLOBAL = new Set(['vehicle_models', 'processed_line_messages']);

function classify(table) {
  if (LEGACY.has(table)) return 'legacy (retire)';
  if (CHILD.has(table)) return 'child (via parent)';
  if (GLOBAL.has(table)) return 'global / review';
  return 'root (needs shop_id)';
}

// ── tables, UNIQUE constraints, foreign keys ──
const tables = new Map();
const createRe = /CREATE TABLE IF NOT EXISTS (\w+) \(([\s\S]*?)\n\s*\) ENGINE/g;
let m;
while ((m = createRe.exec(init))) {
  const [, name, body] = m;
  const uniques = [];
  for (const line of body.split('\n')) {
    const inline = /^\s*(\w+)\s+[A-Z]+(?:\([^)]*\))?[^,]*\bUNIQUE\b/.exec(line);
    if (inline && !/UNIQUE KEY/.test(line)) uniques.push(inline[1]);
    const key = /UNIQUE KEY (\w+) \(([^)]*)\)/.exec(line);
    if (key) uniques.push(`(${key[2].replace(/\s+/g, '')})`);
  }
  const fks = [...body.matchAll(/REFERENCES (\w+)\(/g)].map((x) => x[1]);
  tables.set(name, { uniques, fks });
}
// UNIQUE added later through ALTER TABLE
for (const a of init.matchAll(/ALTER TABLE (\w+)[\s\S]{0,200}?ADD (?:UNIQUE KEY \w+ \(([^)]*)\)|COLUMN (\w+) [^,`]*\bUNIQUE\b)/g)) {
  const t = tables.get(a[1]);
  if (t) t.uniques.push(a[2] ? `(${a[2].replace(/\s+/g, '')})` : a[3]);
}

// ── routes: SQL statement count and which tables each file touches ──
const routeFiles = fs.readdirSync(path.join(SRC, 'routes')).filter((f) => f.endsWith('.js')).sort();
const utilFiles = fs.readdirSync(path.join(SRC, 'utils')).filter((f) => f.endsWith('.js')).sort();
const tableNames = [...tables.keys()];
function scan(dir, files) {
  return files.map((f) => {
    const text = fs.readFileSync(path.join(SRC, dir, f), 'utf8');
    const sql = (text.match(/\b(?:pool|conn)\.(?:query|execute)\(/g) || []).length;
    const touched = tableNames.filter((t) => new RegExp(`\\b${t}\\b`).test(text));
    return { file: `${dir}/${f}`, sql, touched };
  });
}
const code = [...scan('routes', routeFiles), ...scan('utils', utilFiles)].filter((r) => r.sql > 0 || r.touched.length);

// ── report ──
const out = [];
const counts = {};
for (const name of tables.keys()) counts[classify(name)] = (counts[classify(name)] || 0) + 1;
out.push('# SaaS tenant audit (generated by backend/scripts/tenant-audit.js)', '');
out.push(`Tables: ${tables.size} — ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}`);
out.push(`SQL call sites in routes/utils: ${code.reduce((s, r) => s + r.sql, 0)} across ${code.length} files`, '');

out.push('## Tables', '', '| table | treatment | UNIQUE (must become per-shop) | references |', '|---|---|---|---|');
for (const [name, t] of tables) {
  out.push(`| ${name} | ${classify(name)} | ${t.uniques.join(', ') || '-'} | ${[...new Set(t.fks)].join(', ') || '-'} |`);
}

out.push('', '## Code that queries the database (every site needs the shop filter)', '', '| file | SQL calls | tables touched |', '|---|---|---|');
for (const r of code.sort((a, b) => b.sql - a.sql)) out.push(`| ${r.file} | ${r.sql} | ${r.touched.join(', ') || '-'} |`);

const legacyUsers = code.filter((r) => r.touched.some((t) => LEGACY.has(t)));
out.push('', '## Files that still touch the legacy rack / wing-arm tables (to clean up when retiring them)', '');
for (const r of legacyUsers) out.push(`- ${r.file}: ${r.touched.filter((t) => LEGACY.has(t)).join(', ')}`);

const report = out.join('\n') + '\n';
console.log(report);
if (process.argv.includes('--write')) {
  const dest = path.join(__dirname, '..', '..', 'docs', 'saas-tenant-audit.md');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, report);
  console.log(`written: ${dest}`);
}
